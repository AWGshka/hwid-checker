//! Network adapters: current MAC (GetAdaptersAddresses), factory MAC
//! (NDIS OID_802_3_PERMANENT_ADDRESS) and the default gateway's MAC.

use windows::Win32::Devices::Bluetooth::{
    BLUETOOTH_FIND_RADIO_PARAMS, BLUETOOTH_RADIO_INFO, BluetoothFindFirstRadio, BluetoothFindNextRadio,
    BluetoothFindRadioClose, BluetoothGetRadioInfo,
};
use windows::Win32::Foundation::{ERROR_BUFFER_OVERFLOW, HANDLE};
use windows::Win32::System::Registry::HKEY_LOCAL_MACHINE;
use windows::Win32::NetworkManagement::IpHelper::{
    GAA_FLAG_INCLUDE_GATEWAYS, GAA_FLAG_SKIP_ANYCAST, GAA_FLAG_SKIP_DNS_SERVER, GAA_FLAG_SKIP_MULTICAST,
    GetAdaptersAddresses, IP_ADAPTER_ADDRESSES_LH, MIB_IPNET_ROW2, ResolveIpNetEntry2,
};
use windows::Win32::NetworkManagement::Ndis::IfOperStatusUp;
use windows::Win32::Networking::WinSock::{AF_INET, AF_UNSPEC, SOCKADDR_IN};

use crate::report::{Item, Section};
use crate::util::{self, err_value, from_wide, mac_string};

const IOCTL_NDIS_QUERY_GLOBAL_STATS: u32 = 0x0017_0002;
const OID_802_3_PERMANENT_ADDRESS: u32 = 0x0101_0101;
const IF_TYPE_ETHERNET_CSMACD: u32 = 6;
const IF_TYPE_IEEE80211: u32 = 71;

pub struct Adapter {
    name: String,
    guid: String,
    mac: [u8; 6],
    up: bool,
    if_index: u32,
    gateway: Option<SOCKADDR_IN>,
}

pub fn adapters() -> Vec<Adapter> {
    let flags = GAA_FLAG_INCLUDE_GATEWAYS | GAA_FLAG_SKIP_ANYCAST | GAA_FLAG_SKIP_MULTICAST | GAA_FLAG_SKIP_DNS_SERVER;
    let mut size = 32 * 1024u32;
    let mut buf: Vec<u64>; // u64 for alignment of the structures inside
    loop {
        buf = vec![0u64; size as usize / 8 + 1];
        let r = unsafe {
            GetAdaptersAddresses(
                AF_UNSPEC.0 as u32,
                flags,
                None,
                Some(buf.as_mut_ptr() as *mut IP_ADAPTER_ADDRESSES_LH),
                &mut size,
            )
        };
        match r {
            0 => break,
            r if r == ERROR_BUFFER_OVERFLOW.0 => continue,
            _ => return Vec::new(),
        }
    }

    let mut list = Vec::new();
    let mut p = buf.as_ptr() as *const IP_ADAPTER_ADDRESSES_LH;
    while let Some(a) = unsafe { p.as_ref() } {
        p = a.Next;
        if !matches!(a.IfType, IF_TYPE_ETHERNET_CSMACD | IF_TYPE_IEEE80211) || a.PhysicalAddressLength != 6 {
            continue;
        }
        let mut gateway = None;
        let mut g = a.FirstGatewayAddress;
        while let Some(gw) = unsafe { g.as_ref() } {
            let sa = gw.Address.lpSockaddr;
            if !sa.is_null() && unsafe { (*sa).sa_family } == AF_INET {
                gateway = Some(unsafe { *(sa as *const SOCKADDR_IN) });
                break;
            }
            g = gw.Next;
        }
        let mut mac = [0u8; 6];
        mac.copy_from_slice(&a.PhysicalAddress[..6]);
        list.push(Adapter {
            name: unsafe { a.Description.to_string() }.unwrap_or_default(),
            guid: unsafe { a.AdapterName.to_string() }.unwrap_or_default(),
            mac,
            up: a.OperStatus == IfOperStatusUp,
            if_index: unsafe { a.Anonymous1.Anonymous.IfIndex },
            gateway,
        });
    }
    list
}

pub fn mac_section(adapters: &[Adapter]) -> Section {
    let overridden = registry_overrides();
    Section::new("mac", "NETWORK ADAPTERS").items(adapters.iter().map(|a| {
        let factory = permanent_mac(&a.guid);
        let overridden = overridden.iter().any(|g| g.eq_ignore_ascii_case(&a.guid));
        // Bit 1 of the first octet marks a locally administered (software-set) address.
        let local = a.mac[0] & 0x02 != 0;
        let status = match (&factory, overridden) {
            (Ok(f), _) if *f == a.mac => "original",
            (_, true) => "spoofed (registry)",
            (Ok(_), false) if local => "changed (LAA)",
            (Ok(_), false) => "changed",
            (Err(_), false) if local => "locally administered",
            (Err(_), false) => "",
        };
        Item::new()
            .add("adapter", &a.name)
            .add("mac", mac_string(&a.mac))
            .add("factory", factory.map(|f| mac_string(&f)).unwrap_or_else(|e| err_value(&e)))
            .add("mac_status", status)
            .add("link", if a.up { "up" } else { "down" })
    }))
}

/// Interface GUIDs are generated by Windows when the adapter's driver is installed.
pub fn interface_guids_section(adapters: &[Adapter]) -> Section {
    Section::new("interface_guids", "NETWORK INTERFACE GUIDS")
        .items(adapters.iter().map(|a| Item::new().add("adapter", &a.name).add("guid", a.guid.to_uppercase())))
}

const NET_CLASS: &str = r"SYSTEM\CurrentControlSet\Control\Class\{4d36e972-e325-11ce-bfc1-08002be10318}";

/// Interface GUIDs of adapters with a "Network Address" override in their
/// driver key, which is what Device Manager and most MAC changers write.
fn registry_overrides() -> Vec<String> {
    util::reg_subkeys(HKEY_LOCAL_MACHINE, NET_CLASS)
        .into_iter()
        .filter_map(|sub| {
            let path = format!(r"{NET_CLASS}\{sub}");
            util::reg_string(HKEY_LOCAL_MACHINE, &path, "NetworkAddress")?;
            util::reg_string(HKEY_LOCAL_MACHINE, &path, "NetCfgInstanceId")
        })
        .collect()
}

pub fn bluetooth_section() -> Section {
    let s = Section::new("bluetooth", "BLUETOOTH RADIOS");
    let params = BLUETOOTH_FIND_RADIO_PARAMS { dwSize: size_of::<BLUETOOTH_FIND_RADIO_PARAMS>() as u32 };
    let mut radio = HANDLE::default();
    let Ok(find) = (unsafe { BluetoothFindFirstRadio(&params, &mut radio) }) else {
        return s.note("no Bluetooth radio");
    };
    let mut items = Vec::new();
    loop {
        let radio_handle = util::Handle(radio);
        let mut info = BLUETOOTH_RADIO_INFO { dwSize: size_of::<BLUETOOTH_RADIO_INFO>() as u32, ..Default::default() };
        if unsafe { BluetoothGetRadioInfo(radio_handle.0, &mut info) } == 0 {
            // The address is stored little-endian.
            let mut addr = unsafe { info.address.Anonymous.rgBytes };
            addr.reverse();
            items.push(
                Item::new()
                    .add("name", from_wide(&info.szName))
                    .add("address", mac_string(&addr))
                    .add("manufacturer", bt_manufacturer(info.manufacturer))
                    .add("lmp_subversion", info.lmpSubversion.to_string()),
            );
        }
        drop(radio_handle);
        if unsafe { BluetoothFindNextRadio(find, &mut radio) }.is_err() {
            break;
        }
    }
    unsafe {
        let _ = BluetoothFindRadioClose(find);
    }
    s.items(items)
}

fn bt_manufacturer(id: u16) -> String {
    let name = match id {
        0x0002 => "Intel",
        0x000A => "Qualcomm (CSR)",
        0x000D => "Texas Instruments",
        0x000F => "Broadcom",
        0x001D => "Qualcomm",
        0x0046 => "MediaTek",
        0x005D => "Realtek",
        0x0006 => "Microsoft",
        _ => "",
    };
    if name.is_empty() { format!("0x{id:04X}") } else { format!("{name} (0x{id:04X})") }
}

pub fn gateway_section(adapters: &[Adapter]) -> Section {
    Section::new("router_mac", "ROUTER (GATEWAY) MAC")
        .items(adapters.iter().filter_map(|a| {
            let gw = a.gateway?;
            let mac = gateway_mac(a.if_index, gw).map(|m| mac_string(&m)).unwrap_or_else(|| util::NA.into());
            Some(Item::new().add("mac", mac).add("gateway", ipv4(&gw)).add("adapter", &a.name))
        }))
        .note("no IPv4 gateway")
}

fn permanent_mac(guid: &str) -> windows::core::Result<[u8; 6]> {
    let h = util::open_device(&format!(r"\\.\{guid}"), 0)?;
    let out = util::ioctl(&h, IOCTL_NDIS_QUERY_GLOBAL_STATS, &OID_802_3_PERMANENT_ADDRESS.to_le_bytes(), 6)?;
    out.try_into().map_err(|_| windows::core::Error::empty())
}

/// Looks up the neighbour cache, sending an ARP request if the entry is missing.
fn gateway_mac(if_index: u32, gw: SOCKADDR_IN) -> Option<[u8; 6]> {
    let mut row = MIB_IPNET_ROW2::default();
    row.Address.Ipv4 = gw;
    row.InterfaceIndex = if_index;
    unsafe { ResolveIpNetEntry2(&mut row, None) }.ok().ok()?;
    (row.PhysicalAddressLength == 6).then(|| row.PhysicalAddress[..6].try_into().unwrap())
}

fn ipv4(sa: &SOCKADDR_IN) -> String {
    let b = unsafe { sa.sin_addr.S_un.S_addr }.to_ne_bytes();
    format!("{}.{}.{}.{}", b[0], b[1], b[2], b[3])
}
